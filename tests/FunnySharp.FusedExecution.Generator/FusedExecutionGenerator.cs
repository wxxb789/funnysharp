using System;
using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace FunnySharp.FusedExecution.Generator;

/// <summary>
/// Research-only incremental generator for Goal 0039. It recognizes a bounded static subset of
/// existing <c>Summary</c> and <c>Decoder</c> field initializers and emits specialized execution
/// for opt-in partial methods.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class FusedExecutionGenerator : IIncrementalGenerator
{
    internal const string SummaryAttributeName = "FunnySharp.FusedSummaryAttribute";
    internal const string DecodingAttributeName = "FunnySharp.FusedDecodingAttribute";

    private const string AttributeSource = """
        // <auto-generated/>
        #nullable enable
        namespace FunnySharp
        {
            [global::System.AttributeUsage(global::System.AttributeTargets.Method, AllowMultiple = false, Inherited = false)]
            internal sealed class FusedSummaryAttribute : global::System.Attribute
            {
                internal FusedSummaryAttribute(string fieldName) => FieldName = fieldName;

                internal string FieldName { get; }
            }

            [global::System.AttributeUsage(global::System.AttributeTargets.Method, AllowMultiple = false, Inherited = false)]
            internal sealed class FusedDecodingAttribute : global::System.Attribute
            {
                internal FusedDecodingAttribute(string fieldName) => FieldName = fieldName;

                internal string FieldName { get; }
            }
        }
        """;

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(
            static output => output.AddSource(
                "FunnySharp.FusedExecution.Attributes.g.cs",
                SourceText.From(AttributeSource, Encoding.UTF8)));

        var summaries = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                SummaryAttributeName,
                static (_, _) => true,
                static (attributeContext, cancellationToken) => FusionTransform.Transform(
                    attributeContext,
                    FusionKind.Summary,
                    cancellationToken))
            .Where(static request => request is not null);

        var decoders = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                DecodingAttributeName,
                static (_, _) => true,
                static (attributeContext, cancellationToken) => FusionTransform.Transform(
                    attributeContext,
                    FusionKind.Decoding,
                    cancellationToken))
            .Where(static request => request is not null);

        context.RegisterSourceOutput(
            summaries,
            static (output, request) => Emit(output, request!));

        context.RegisterSourceOutput(
            decoders,
            static (output, request) => Emit(output, request!));
    }

    private static void Emit(SourceProductionContext output, FusionRequest request)
    {
        foreach (var diagnostic in request.Diagnostics)
        {
            output.ReportDiagnostic(diagnostic);
        }

        if (request.Source is not null)
        {
            output.AddSource(request.HintName, SourceText.From(request.Source, Encoding.UTF8));
        }
    }
}

internal enum FusionKind
{
    Summary,
    Decoding,
}

internal sealed class FusionRequest : IEquatable<FusionRequest>
{
    internal FusionRequest(
        string hintName,
        string? source,
        ImmutableArray<Diagnostic> diagnostics)
    {
        HintName = hintName;
        Source = source;
        Diagnostics = diagnostics;
    }

    internal string HintName { get; }

    internal string? Source { get; }

    internal ImmutableArray<Diagnostic> Diagnostics { get; }

    public bool Equals(FusionRequest? other)
    {
        if (other is null)
        {
            return false;
        }

        if (ReferenceEquals(this, other))
        {
            return true;
        }

        if (!string.Equals(HintName, other.HintName, StringComparison.Ordinal)
            || !string.Equals(Source, other.Source, StringComparison.Ordinal)
            || Diagnostics.Length != other.Diagnostics.Length)
        {
            return false;
        }

        for (var index = 0; index < Diagnostics.Length; index++)
        {
            if (!DiagnosticEquals(Diagnostics[index], other.Diagnostics[index]))
            {
                return false;
            }
        }

        return true;
    }

    public override bool Equals(object? obj) => Equals(obj as FusionRequest);

    public override int GetHashCode()
    {
        unchecked
        {
            var hash = (HintName.GetHashCode() * 397) ^ (Source?.GetHashCode() ?? 0);
            return (hash * 397) ^ Diagnostics.Length;
        }
    }

    private static bool DiagnosticEquals(Diagnostic left, Diagnostic right) =>
        string.Equals(left.Id, right.Id, StringComparison.Ordinal)
        && left.Severity == right.Severity
        && left.Location.SourceSpan.Equals(right.Location.SourceSpan)
        && string.Equals(left.GetMessage(), right.GetMessage(), StringComparison.Ordinal);
}

internal static class FusionDiagnostics
{
    private const string Category = "FunnySharp.FusedExecution";

    internal static readonly DiagnosticDescriptor UnsupportedSummary = new(
        id: "FS3901",
        title: "Summary declaration is outside the fused-execution subset",
        messageFormat: "{0}",
        category: Category,
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    internal static readonly DiagnosticDescriptor UnsupportedDecoder = new(
        id: "FS3902",
        title: "Decoder declaration is outside the fused-execution subset",
        messageFormat: "{0}",
        category: Category,
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    internal static readonly DiagnosticDescriptor InvalidMethod = new(
        id: "FS3903",
        title: "Fused-execution method declaration is invalid",
        messageFormat: "{0}",
        category: Category,
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    internal static readonly DiagnosticDescriptor InvalidField = new(
        id: "FS3904",
        title: "Fused-execution field declaration is invalid",
        messageFormat: "{0}",
        category: Category,
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    internal static Diagnostic UnsupportedSummaryAt(SyntaxNode node, string message) =>
        Diagnostic.Create(UnsupportedSummary, node.GetLocation(), message);

    internal static Diagnostic UnsupportedDecoderAt(SyntaxNode node, string message) =>
        Diagnostic.Create(UnsupportedDecoder, node.GetLocation(), message);

    internal static Diagnostic InvalidMethodAt(SyntaxNode node, string message) =>
        Diagnostic.Create(InvalidMethod, node.GetLocation(), message);

    internal static Diagnostic InvalidFieldAt(SyntaxNode node, string message) =>
        Diagnostic.Create(InvalidField, node.GetLocation(), message);
}
